"""Compile the standalone AVF compute shader locally with the Windows SDK.

No game shader dump is modified. The generated bytecode header lives only in
the pinned local Dagor checkout. The driver retains static bytecode/metadata
for device reset, so do not feed it transient compiler buffers.
"""
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

SHADER = Path(__file__).resolve().parents[1] / "engine/shaders/ke_avf_reduce.hlsl"


def find_fxc():
    direct = shutil.which("fxc.exe")
    if direct:
        return Path(direct)
    roots = [Path(os.environ.get("WindowsSdkDir", r"C:\Program Files (x86)\Windows Kits\10"))]
    for root in roots:
        candidates = sorted(root.glob("bin/*/x64/fxc.exe"), reverse=True)
        if candidates:
            return candidates[0]
    return None


def prepare_avf_shader(dagor):
    target = dagor / "prog/tools/sceneTools/daEditorX/services/dynRenderSrv/ke_avf_reduce_bytecode.h"
    fxc = find_fxc()
    if fxc is None:
        raise ValueError("AVF GPU build requires fxc.exe from Windows SDK (Developer PowerShell)")
    lines = ["#pragma once", "#include <cstdint>"]
    for shader, symbol in ((SHADER, "keAvfReduceBytecode"),
                           (SHADER.with_name("ke_fixed_reduce.hlsl"), "keFixedReduceBytecode")):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "reduce.cso"
            subprocess.run([str(fxc), "/nologo", "/T", "cs_5_0", "/E", "main",
                            "/O3", "/Gis", "/Fo", str(out), str(shader)], check=True)
            code = out.read_bytes()
        if not code.startswith(b"DXBC") or len(code) < 32:
            raise ValueError(f"Invalid DXBC output: {shader}")
        lines.append(f"alignas(4) static constexpr uint8_t {symbol}[] = {{")
        for i in range(0, len(code), 16):
            lines.append("  " + ", ".join(f"0x{x:02x}" for x in code[i:i+16]) + ",")
        lines.append("};")
        print(f"[KE] AVF_SHADER_OK shader={shader.name} bytes={len(code)}", flush=True)
    data = ("\n".join(lines)+"\n").encode("ascii")
    if not target.exists() or target.read_bytes() != data:
        target.write_bytes(data)
